#   位置典型偏差 ~ 10 mm  → w = 1/(0.01)^2  = 1e4
#   高度典型偏差 ~  5 mm  → w = 1/(0.005)^2 = 4e4
#   角度典型偏差 ~  5 deg ≈ 0.087 rad → w = 1/(0.087)^2 ≈ 130
#   速度、角速度同理给一个温和的惩罚
# 这组值是**起点**,不是最优解;实际表现由 sim/run_lqr.py 验证后再调。
